describe('Real MediaPipe 512-D Hybrid Biometric Anti-Impostor Gate', () => {
  afterEach(() => {
    vi.restoreAllMocks();
  });

  it('identifies all real hybrid vectors via common-mode signature while keeping synthetic vectors separate', () => {
    for (const s of REAL_SAMPLES) {
      expect(isRealHybridBiometricVector(l2Normalize(s.frontalCentroid))).toBe(true);
      expect(isRealHybridBiometricVector(l2Normalize(s.probeFrame))).toBe(true);
    }

    const synthetic = new Array(512).fill(0);
    synthetic[0] = 1;
    expect(isRealHybridBiometricVector(synthetic)).toBe(false);
  });

  it('accepts every genuinely enrolled subject matching their own frontal centroid (>= 85%)', () => {
    for (const subject of REAL_SAMPLES) {
      const hybrid = verifyHybridBiometricIdentity(subject.probeFrame, subject.frontalCentroid);
      expect(hybrid.isRealHybrid).toBe(true);
      expect(hybrid.passesHybridGate).toBe(true);
      expect(hybrid.rawCos).toBeGreaterThanOrEqual(0.925);
      expect(hybrid.whitenedCos).toBeGreaterThanOrEqual(0.70);

      const evalRes = evaluateBiometricMatch(subject.probeFrame, subject.frontalCentroid);
      expect(evalRes.isMatch).toBe(true);
      expect(evalRes.similarityPercentage).toBeGreaterThanOrEqual(85);
    }
  });

  it('strictly rejects every cross-person combination even though raw cosine is 0.70–0.88 (< 50%)', () => {
    for (let i = 0; i < REAL_SAMPLES.length; i++) {
      for (let j = 0; j < REAL_SAMPLES.length; j++) {
        if (i === j) continue;
        const probeOwner = REAL_SAMPLES[i];
        const targetAccount = REAL_SAMPLES[j];

        const hybrid = verifyHybridBiometricIdentity(probeOwner.probeFrame, targetAccount.frontalCentroid);
        expect(hybrid.isRealHybrid).toBe(true);
        expect(hybrid.passesHybridGate).toBe(false);

        const evalRes = evaluateBiometricMatch(probeOwner.probeFrame, targetAccount.frontalCentroid);
        expect(evalRes.isMatch).toBe(false);
        expect(evalRes.similarityPercentage).toBeLessThan(50);
      }
    }
  });

  it('rejects unseen stranger probes (leave-one-out DB without probe owner) in both RPC fast-path and patients fallback', async () => {
    const client = new ApiClient('/api');
    const stranger = REAL_SAMPLES[0]; // Remove Subject A from DB to simulate unregistered stranger scanning
    const enrolledOnly = REAL_SAMPLES.slice(1).map((s, idx) => ({
      id: s.id,
      hn: s.hn,
      first_name: s.label,
      last_name: 'Patient',
      age: 40 + idx,
      sex: 'male',
      registration_status: 'active',
      history: {
        biometric_10_shot: {
          frontal_centroid: s.frontalCentroid,
          overall_centroid: s.frontalCentroid,
          raw_frames: [{ pose: 'front', vector: s.frontalCentroid }],
        },
      },
    }));

    // Simulate Cloudflare Worker /api 404 delegation + Supabase RPC returning high raw SQL similarity (~0.87)
    vi.spyOn(globalThis, 'fetch').mockImplementation(async (input) => {
      const url = typeof input === 'string' ? input : input.toString();
      if (url.startsWith('/api/')) {
        return new Response(JSON.stringify({ error: 'DELEGATE_TO_SUPABASE_CLOUD' }), {
          status: 404,
          headers: { 'Content-Type': 'application/json' },
        });
      }
      if (url.includes('/rest/v1/rpc/match_patient_face')) {
        return new Response(
          JSON.stringify([
            { ...enrolledOnly[0], similarity: 0.87, distance: 0.51 },
            { ...enrolledOnly[1], similarity: 0.72, distance: 0.74 },
          ]),
          { status: 200, headers: { 'Content-Type': 'application/json' } }
        );
      }
      if (url.includes('/rest/v1/patients')) {
        return new Response(JSON.stringify(enrolledOnly), {
          status: 200,
          headers: { 'Content-Type': 'application/json' },
        });
      }
      return new Response(JSON.stringify([]), { status: 200 });
    });

    const strangerRes = await client.smartOnboarding.scanLogin({ probe: stranger.probeFrame });
    expect(strangerRes.matched).toBe(false);
    expect(strangerRes.patient).toBeNull();
    expect(strangerRes.similarityPercentage ?? 0).toBeLessThan(50);

    // Genuine enrolled user Subject B still logs into ONLY Subject B
    const genuineRes = await client.smartOnboarding.scanLogin({ probe: REAL_SAMPLES[1].probeFrame });
    expect(genuineRes.matched).toBe(true);
    expect(genuineRes.patient?.hn).toBe(REAL_SAMPLES[1].hn);
  });
});
